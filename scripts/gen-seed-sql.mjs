// Generates supabase/seed.sql from src/data/catalog.js so demo mode and Supabase share one catalog.
// Usage: npm run seed:sql
import { writeFileSync } from 'node:fs'
import { specialties, hospitals, doctors } from '../src/data/catalog.js'

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arrInt = (a) => `'{${a.join(',')}}'::int[]`
const arrText = (a) => `'{${a.map((x) => `"${x}"`).join(',')}}'::text[]`

const lines = ['-- Generated by scripts/gen-seed-sql.mjs. Safe to run more than once.', 'begin;', '']

lines.push('insert into public.specialties (slug, name, icon, blurb) values')
lines.push(specialties.map((s) => `  (${q(s.slug)}, ${q(s.name)}, ${q(s.icon)}, ${q(s.blurb)})`).join(',\n'))
lines.push('on conflict (slug) do update set name = excluded.name, icon = excluded.icon, blurb = excluded.blurb;', '')

lines.push('insert into public.hospitals (id, name, address, lat, lng, phone, rating, color, image) values')
lines.push(
  hospitals
    .map((h) => `  (${q(h.id)}, ${q(h.name)}, ${q(h.address)}, ${h.lat}, ${h.lng}, ${q(h.phone)}, ${h.rating}, ${q(h.color)}, ${q(h.image)})`)
    .join(',\n'),
)
lines.push(
  'on conflict (id) do update set name = excluded.name, address = excluded.address, lat = excluded.lat, lng = excluded.lng, phone = excluded.phone, rating = excluded.rating, color = excluded.color, image = excluded.image;',
  '',
)

lines.push('insert into public.doctors (id, name, specialty, hospital_id, experience_years, patients, rating, reviews_count, fee, days, slots, bio, photo, portrait) values')
lines.push(
  doctors
    .map(
      (d) =>
        `  (${q(d.id)}, ${q(d.name)}, ${q(d.specialty)}, ${q(d.hospital_id)}, ${d.experience_years}, ${d.patients}, ${d.rating}, ${d.reviews_count}, ${d.fee}, ${arrInt(d.days)}, ${arrText(d.slots)}, ${q(d.bio)}, ${q(d.photo)}, ${q(d.portrait)})`,
    )
    .join(',\n'),
)
lines.push(
  'on conflict (id) do update set name = excluded.name, specialty = excluded.specialty, hospital_id = excluded.hospital_id, experience_years = excluded.experience_years, patients = excluded.patients, fee = excluded.fee, days = excluded.days, slots = excluded.slots, bio = excluded.bio, photo = excluded.photo, portrait = excluded.portrait;',
  '',
  'commit;',
  '',
)

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'))
console.log('Wrote supabase/seed.sql')
